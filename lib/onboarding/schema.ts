export function mergeDefaults(saved: unknown): OnboardingValues {
  const defaults = createDefaults()
  const parsed = onboardingSchema.safeParse({ ...defaults, ...(saved as object) })
  if (!parsed.success) return defaults
  return {
    ...defaults,
    ...parsed.data,
    regionRanks: { ...defaults.regionRanks, ...parsed.data.regionRanks },
    metrics: {
      year1: { ...defaults.metrics.year1, ...parsed.data.metrics.year1 },
      year2: { ...defaults.metrics.year2, ...parsed.data.metrics.year2 },
      year3: { ...defaults.metrics.year3, ...parsed.data.metrics.year3 },
    },
    projections: Object.fromEntries(
      REGIONS.map((region) => [
        region.id,
        {
          ...defaults.projections[region.id],
          ...parsed.data.projections[region.id],
        },
      ])
    ) as OnboardingValues["projections"],
    contacts: {
      sponsor: { ...defaults.contacts.sponsor, ...parsed.data.contacts.sponsor },
      compliance: { ...defaults.contacts.compliance, ...parsed.data.contacts.compliance },
      technical: { ...defaults.contacts.technical, ...parsed.data.contacts.technical },
      operations: { ...defaults.contacts.operations, ...parsed.data.contacts.operations },
      finance: { ...defaults.contacts.finance, ...parsed.data.contacts.finance },
    },
    aml: {
      policy: { ...defaults.aml.policy, ...parsed.data.aml.policy },
      kyc: { ...defaults.aml.kyc, ...parsed.data.aml.kyc },
      monitoring: { ...defaults.aml.monitoring, ...parsed.data.aml.monitoring },
      risk: { ...defaults.aml.risk, ...parsed.data.aml.risk },
      review: { ...defaults.aml.review, ...parsed.data.aml.review },
      other: { ...defaults.aml.other, ...parsed.data.aml.other },
    },
    fees: parsed.data.fees.length ? parsed.data.fees : defaults.fees,
    credentialPositions: {
      number: { ...defaults.credentialPositions.number, ...parsed.data.credentialPositions.number },
      name: { ...defaults.credentialPositions.name, ...parsed.data.credentialPositions.name },
      expiry: { ...defaults.credentialPositions.expiry, ...parsed.data.credentialPositions.expiry },
      cvv: { ...defaults.credentialPositions.cvv, ...parsed.data.credentialPositions.cvv },
    },
    sandboxUsers: parsed.data.sandboxUsers.length
      ? parsed.data.sandboxUsers
      : defaults.sandboxUsers,
    screenNotes: { ...defaults.screenNotes, ...parsed.data.screenNotes },
    goLiveChecks: { ...defaults.goLiveChecks, ...parsed.data.goLiveChecks },
  }
}
